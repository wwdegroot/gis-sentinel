//! REST API layer (task 2.1): `AppState`-independent state, typed errors and
//! extraction wrappers so integration tests can build the router from the lib
//! crate without booting the binary.
//!
//! The API keeps its own [`ApiState`] (db + queue pools); `main.rs` merges the
//! API sub-router (resolved to `Router<()>` via `with_state`) with the
//! WebSocket demo router, which still uses the binary's `AppState`.

pub mod alert_points;

use std::collections::HashMap;
use std::sync::Arc;

use axum::extract::{FromRequest, FromRequestParts, Query, Request};
use axum::http::request::Parts;
use axum::http::StatusCode;
use axum::response::{IntoResponse, Response};
use axum::{Json, Router};
use serde::de::DeserializeOwned;
use serde_json::json;
use thiserror::Error;

use crate::db::repo::{ActiveAlertStore, AlertPointRepository, ProbeResultStore, RepoError};
use crate::queue::{ProbeQueue, QueueError};

/// Probe request timeout handed to `ProbeJob` (task 2.1 decision: the
/// `alert_points` schema has no timeout column yet; configurable timeout is
/// deferred until the worker in task 2.3 needs it).
pub const DEFAULT_PROBE_TIMEOUT_MS: i32 = 10_000;

/// State for the `/api/v1` routers (built once in `main.rs`, or per test).
///
/// Storage is abstracted behind repository/queue traits (see `docs/tests.md`)
/// so tests can wire the in-memory fakes from `db::repo::fake` / `queue::fake`
/// instead of live PostgreSQL/Valkey pools.
#[derive(Debug, Clone)]
pub struct ApiState {
    /// `alert_points` repository.
    pub alert_points: Arc<dyn AlertPointRepository>,
    /// `probe_results` store.
    pub probe_results: Arc<dyn ProbeResultStore>,
    /// `active_alerts` store.
    pub active_alerts: Arc<dyn ActiveAlertStore>,
    /// Probe job queue.
    pub queue: Arc<dyn ProbeQueue>,
}

/// All REST routes under `/api/v1`.
///
/// The `/api/v1` prefix is baked in here (single source of truth) so the
/// production router and the integration tests can't drift apart.
pub fn router() -> Router<ApiState> {
    use axum::routing::{get, post};
    Router::new()
        .nest(
            "/api/v1",
            Router::new()
                .route(
                    "/alert-points",
                    get(alert_points::list).post(alert_points::create),
                )
                .route(
                    "/alert-points/{id}",
                    get(alert_points::get)
                        .put(alert_points::update)
                        .delete(alert_points::delete),
                )
                .route("/alert-points/{id}/test", post(alert_points::test)),
        )
}

/// Typed API error mapped to the uniform JSON error envelope.
///
/// Handler bodies return `Result<impl IntoResponse, ApiError>` and propagate
/// with `?` via the `From` conversions generated by `thiserror`.
#[derive(Debug, Error)]
pub enum ApiError {
    /// Structurally valid payload that failed validation rules.
    #[error("validation failed")]
    Validation(HashMap<String, Vec<String>>),
    /// Invalid request shape (JSON/URL extraction failures, bad query params).
    #[error("{0}")]
    BadRequest(String),
    /// Requested resource does not exist.
    #[error("resource not found")]
    NotFound,
    /// Database/repository error; `NotFound` (and `RowNotFound`) translate to
    /// 404, uniqueness conflicts to 409, everything else 500.
    #[error("repository error")]
    Repository(#[from] RepoError),
    /// Valkey/Redis queue unreachable; surfaced as 503.
    #[error("queue unavailable")]
    QueueUnavailable(#[from] QueueError),
}

impl IntoResponse for ApiError {
    fn into_response(self) -> Response {
        let (status, code, message, details) = match &self {
            ApiError::Validation(errors) => (
                StatusCode::BAD_REQUEST,
                "validation",
                "validation failed".to_string(),
                Some(json!(errors)),
            ),
            ApiError::BadRequest(message) => (
                StatusCode::BAD_REQUEST,
                "bad_request",
                message.clone(),
                None,
            ),
            ApiError::NotFound => (
                StatusCode::NOT_FOUND,
                "not_found",
                "resource not found".to_string(),
                None,
            ),
            ApiError::Repository(e) => match e {
                RepoError::NotFound => (
                    StatusCode::NOT_FOUND,
                    "not_found",
                    "resource not found".to_string(),
                    None,
                ),
                RepoError::Conflict => (
                    StatusCode::CONFLICT,
                    "conflict",
                    "conflicting resource state".to_string(),
                    None,
                ),
                RepoError::Db(sqlx::Error::RowNotFound) => (
                    StatusCode::NOT_FOUND,
                    "not_found",
                    "resource not found".to_string(),
                    None,
                ),
                other => {
                    tracing::error!(error = ?other, "database error while handling API request");
                    (
                        StatusCode::INTERNAL_SERVER_ERROR,
                        "database_error",
                        "database error".to_string(),
                        None,
                    )
                }
            },
            ApiError::QueueUnavailable(e) => {
                tracing::error!(error = ?e, "queue unavailable while handling API request");
                (
                    StatusCode::SERVICE_UNAVAILABLE,
                    "queue_unavailable",
                    "queue unavailable".to_string(),
                    None,
                )
            }
        };

        let body = json!({
            "error": {
                "code": code,
                "message": message,
                "details": details,
            }
        });
        (status, Json(body)).into_response()
    }
}

/// Contract implemented by request DTOs: derive-based validation plus any
/// structural checks the `validator` crate cannot express on raw JSON values.
pub trait ValidateRequest {
    fn validate_request(&self) -> Result<(), HashMap<String, Vec<String>>>;
}

/// `Json` extractor that maps deserialization failures into the API error
/// envelope and runs the DTO's [`ValidateRequest`] rules.
pub struct ValidatedJson<T>(pub T);

impl<S, T> FromRequest<S> for ValidatedJson<T>
where
    S: Send + Sync,
    T: DeserializeOwned + ValidateRequest,
{
    type Rejection = ApiError;

    async fn from_request(req: Request, state: &S) -> Result<Self, Self::Rejection> {
        let Json(value) = Json::<T>::from_request(req, state)
            .await
            .map_err(|rejection| ApiError::BadRequest(format!("invalid JSON body: {rejection}")))?;
        value.validate_request().map_err(ApiError::Validation)?;
        Ok(ValidatedJson(value))
    }
}

/// `Query` extractor that maps invalid query parameters into the envelope.
pub struct ApiQuery<T>(pub T);

impl<S, T> FromRequestParts<S> for ApiQuery<T>
where
    S: Send + Sync,
    T: DeserializeOwned,
{
    type Rejection = ApiError;

    async fn from_request_parts(parts: &mut Parts, state: &S) -> Result<Self, Self::Rejection> {
        let Query(value) =
            Query::<T>::from_request_parts(parts, state)
                .await
                .map_err(|rejection| {
                    ApiError::BadRequest(format!("invalid query parameters: {rejection}"))
                })?;
        Ok(ApiQuery(value))
    }
}

/// Convert `validator::ValidationErrors` into the field -> messages map used
/// by the error envelope's `details` object.
pub fn errors_to_map(e: validator::ValidationErrors) -> HashMap<String, Vec<String>> {
    use validator::ValidationErrorsKind;
    let mut out: HashMap<String, Vec<String>> = HashMap::new();
    for (field, kind) in e.errors() {
        let messages = match kind {
            ValidationErrorsKind::Field(errors) => errors
                .iter()
                .map(|p| {
                    p.message
                        .clone()
                        .unwrap_or(std::borrow::Cow::Borrowed("invalid value"))
                        .to_string()
                })
                .collect(),
            // nested structs never occur in our flat DTOs; report generically
            _ => vec!["invalid value".to_string()],
        };
        out.insert(field.to_string(), messages);
    }
    out
}
